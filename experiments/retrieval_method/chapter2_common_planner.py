"""统一8B公开问题规划器；无图、无原文、无gold输入，输出跨方法共享。"""
import argparse
import hashlib
import importlib
import json
import os
from pathlib import Path
import re
import shutil
import sys

from chapter2_production_guard import install


PROMPT = """将公开blastFoam资料问题拆成检索需求，只做规划，不作答、不猜教程选了什么模型或参数值。
忠实翻译问题为英文，必须保留原有案例/文件/字典字段技术标识；不要由记忆增添未给的模型名称、数值、运行结论或条件。
把实际教程取值/声明、手册用途或条件、公式单位/默认值、多文件命令等明确所问内容拆为最多8条needs。每条明确tutorial或manual及对象/字段，别用一个泛称model覆盖所有字段。
单来源问题只保留该来源需求，不能机械加另一来源。技术名称只来自公开问题，英语自然翻译不作为事实证据。
仅输出JSON：{"translation":"忠实英文表达","needs":["tutorial: 实际所问案例及字段","manual: 实际所问定义或条件"]}。
needs的每项优先写字符串；也接受精确结构{"source":"tutorial或manual","object":"公开问题中的对象","field":"明确所问内容"}，不超过8项。
不要输出答案、gold或任何已经满足条件的判断。"""


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def save(path, value):
    if path.exists():
        raise FileExistsError("immutable public planning artifact")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+"\n")


def compile_plan(plan, question):
    if not isinstance(plan, dict) or not isinstance(plan.get("translation"), str) or not plan["translation"].strip():
        raise ValueError("invalid translation")
    if not isinstance(plan.get("needs"), list) or not 1 <= len(plan["needs"]) <= 8:
        raise ValueError("invalid needs count")
    needs = []
    for need in plan["needs"]:
        if isinstance(need, str) and need.strip():
            needs.append(need)
        elif isinstance(need, dict) and set(need)=={"source", "object", "field"} and need["source"] in {"tutorial", "manual"} and all(isinstance(need[k], str) and need[k].strip() for k in need):
            needs.append(need["source"]+": "+need["object"]+" / "+need["field"])
        else:
            raise ValueError("invalid need schema")
    return {"translation": plan["translation"], "needs": needs,
            "identifiers": sorted(set(re.findall(r"[A-Za-z_][A-Za-z_0-9./<>+-]*", question)))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("prepare", "run"))
    parser.add_argument("--questions", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--settings-file", type=Path)
    args = parser.parse_args()
    if os.environ.get("PYTHONHASHSEED") != "0":
        raise ValueError("set PYTHONHASHSEED=0")
    guard = install(offline=False)
    questions = json.loads(args.questions.read_text())
    if any(q["split"] != "dev" for q in questions):
        raise ValueError("development only until final implementation/protocol freeze")
    if args.command == "prepare":
        if args.output.exists():
            raise FileExistsError("new planner version required")
        source = Path(__file__).parent
        names = (Path(__file__).name, "chapter2_production_guard.py", "chapter2_aliyun_config.py", "navigation_qa.py", "graphify_qa.py", "graphify_query_backend.py")
        runtime = args.output / "runtime"
        runtime.mkdir(parents=True)
        for name in names:
            shutil.copy2(source / name, runtime / name)
        save(args.output / "questions.json", questions)
        save(args.output / "protocol.json", {"schema": "development-common-public-planner-v3", "major_round": 3, "model": "qwen3-8b",
             "endpoint": "https://dashscope.aliyuncs.com/compatible-mode/v1/chat/completions", "role": "common_query_planning_development",
             "generation": {"temperature": 0, "enable_thinking": False, "max_tokens": 700, "response_format": {"type": "json_object"}},
             "instruction": PROMPT, "planned_calls": len(questions), "public_questions_sha256": sha(args.output / "questions.json"),
             "original_public_questions_sha256": sha(args.questions), "guard": guard, "python_hash_seed": "0",
             "runtime_sha256": {name: sha(runtime / name) for name in names},
             "invalid_structure_policy": "keep invalid response; downstream uses unchanged raw question and empty needs, no quality resampling",
             "transport_retry": "identical request only via existing frozen transport; failed attempts retained",
             "sharing": "one output per public development question, identical output reused across method arms; planner cost recorded separately",
             "identifier_policy": "deterministic literal extraction from unchanged public question; not generated by model",
             "needs_schema": "bounded1-8 strings or exact source/object/field dictionaries; dictionaries serialized to strings before shared retrieval",
             "limits": "开发公共规划，不是正式协议；原始问题始终保留，规划无原文或gold，不用模型知识当答案证据。"})
        return
    runtime = args.output / "runtime"
    protocol = json.loads((args.output / "protocol.json").read_text())
    if Path(__file__).resolve() != (runtime / Path(__file__).name).resolve():
        raise ValueError("run frozen planner snapshot")
    if sha(args.questions) != protocol["original_public_questions_sha256"] or sha(args.output / "questions.json") != protocol["public_questions_sha256"]:
        raise ValueError("public planning question drift")
    for name, expected in protocol["runtime_sha256"].items():
        if sha(runtime / name) != expected:
            raise ValueError("planning runtime drift")
    sys.path.insert(0, str(runtime))
    qa = importlib.import_module("navigation_qa")
    config = importlib.import_module("chapter2_aliyun_config")
    transport = importlib.import_module("graphify_qa")
    config.configure_qa(qa)
    transport.SECRET = config.read_settings(args.settings_file)
    transport.reset_transport_circuit()
    for question in questions:
        folder = args.output / "responses" / question["id"]
        if (folder / "compiled.json").exists():
            continue
        request = qa.request([{"role": "system", "content": protocol["instruction"]},
                              {"role": "user", "content": qa.wire({"question": question["question"]})}], final=False)
        response = transport.fetch(folder, "plan", request, transport.SECRET)
        try:
            choice = qa.choice(response)
            if choice["finish_reason"] != "stop":
                raise ValueError("planning response truncated")
            plan = qa.decode_json_prefix(choice["message"]["content"])
            plan = compile_plan(plan, question["question"])
            compiled = {"status": "valid_structure", "plan": plan}
        except (ValueError, TypeError, KeyError) as error:
            compiled = {"status": "invalid_structure", "error": str(error), "plan": {"translation": "", "needs": [], "identifiers": []}}
        save(folder / "compiled.json", {**compiled, "question": question, "response_sha256": sha(folder / "plan.json"),
             "protocol_sha256": sha(args.output / "protocol.json"), "limits": "结构有效不证明翻译完整忠实；另查遗漏/猜测，但不按开发成绩重新请求。"})
        print("DONE", question["id"], compiled["status"], flush=True)


if __name__ == "__main__":
    main()
