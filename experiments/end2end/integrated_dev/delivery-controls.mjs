import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {verifyManifest, canonical} from './delivery-check-core.mjs';

const {defineTool} = await import(pathToFileURL(path.join(process.env.C3_RUNTIME, 'packages/core/tools/lib/index.js')).href);
export const name = 'delivery-controls';
export const inject = ['tools'];

export function apply(ctx) {
  ctx.tools.register(defineTool({
    name: 'verify_artifact_manifest',
    description: 'Read-only SHA256 check. manifest is workspace JSON with files:{relativePath:sha256}; directory is the workspace-relative base for those files. Returns integer counts and differences. Does not assemble delivery or judge numerical correctness.',
    parameters: {
      manifest: {type: 'string', required: true, description: 'Workspace-relative manifest JSON'},
      directory: {type: 'string', required: true, description: 'Workspace-relative file directory'},
    },
    output: {schema: {type: 'object', additionalProperties: false, properties: {result: {type: 'string', required: true}}},
      render: (_args, value) => [{type: 'text', text: value.result}]},
    async execute({manifest, directory}, exec) {
      return {result: JSON.stringify(verifyManifest(process.cwd(), manifest, directory, exec.signal))};
    },
  }));

  // Opt-in session-local guard. It stops an action, never completes an agent turn.
  const states = new WeakMap(), unscoped = {}, denied = new Set();
  const owner = exec => exec.agent ?? unscoped;
  const signature = exec => {
    const args = exec.arguments && typeof exec.arguments === 'object' ? exec.arguments : {};
    const {description, ...argumentsWithoutLabel} = args;
    return JSON.stringify(canonical(argumentsWithoutLabel));
  };
  ctx.on('tools/pre-execute', async (exec, next) => {
    const previous = states.get(owner(exec));
    if (exec.name === 'pwsh' && previous?.count >= 3 && signature(exec) === previous.signature) {
      denied.add(exec.token);
      return {kind: 'deny', reason: 'REPEATED_UNCHANGED_ACTION: this shell call already returned the same successful output three consecutive times. It was not executed again. Review the existing result or take a different action; no delivery files were generated by this guard. Time passing alone does not reset the guard. For external-state polling, use a different job/status or read action before retrying.'};
    }
    return next();
  });
  ctx.on('tools/result', (exec, result) => {
    if (denied.delete(exec.token)) return;
    const key = owner(exec), value = result.value;
    if (exec.name !== 'pwsh' || result.isError || value?.kind !== 'foreground' || value.exitCode !== 0 ||
        value.timedOut || value.aborted || value.stdout?.truncated || value.stderr?.truncated) {
      states.delete(key);
      return;
    }
    const current = signature(exec);
    const hash = createHash('sha256').update(JSON.stringify([value.stdout.text, value.stderr.text])).digest('hex');
    const previous = states.get(key);
    const count = previous?.signature === current && previous.hash === hash ? previous.count + 1 : 1;
    states.set(key, {signature: current, hash, count});
  });
}
